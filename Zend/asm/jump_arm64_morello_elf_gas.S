.file "jump_arm64_aapcs_elf_gas.S"
.text
.align  2
.global jump_fcontext
.type   jump_fcontext, %function
jump_fcontext:
    # prepare stack for GP + FPU
    sub  csp, csp, #0x110

    # save d8 - d15
    stp  d8,  d9,  [csp, #0x00]
    stp  d10, d11, [csp, #0x10]
    stp  d12, d13, [csp, #0x20]
    stp  d14, d15, [csp, #0x30]

    # save x19-x30
    stp  c19, c20, [csp, #0x40]
    stp  c21, c22, [csp, #0x60]
    stp  c23, c24, [csp, #0x80]
    stp  c25, c26, [csp, #0xa0]
    stp  c27, c28, [csp, #0xc0]
    stp  c29, c30, [csp, #0xe0]

    # save LR as PC
    str  c30, [csp, #0x100]

    # store RSP (pointing to context-data) in C0
    mov  c4, csp

    # restore RSP (pointing to context-data) from C1
    mov  csp, c0

    # load d8 - d15
    ldp  d8,  d9,  [csp, #0x00]
    ldp  d10, d11, [csp, #0x10]
    ldp  d12, d13, [csp, #0x20]
    ldp  d14, d15, [csp, #0x30]

    # load x19-x30
    ldp  c19, c20, [csp, #0x40]
    ldp  c21, c22, [csp, #0x60]
    ldp  c23, c24, [csp, #0x80]
    ldp  c25, c26, [csp, #0xa0]
    ldp  c27, c28, [csp, #0xc0]
    ldp  c29, c30, [csp, #0xe0]

    # return transfer_t from jump
    # pass transfer_t as first arg in context function
    # C0 == FCTX, C1 == DATA
    mov c0, c4

    # load pc
    ldr  c4, [csp, #0x100]

    # restore stack from GP + FPU
    add  csp, csp, #0x110

    ret c4
.size   jump_fcontext,.-jump_fcontext
# Mark that we don't need executable stack.
.section .note.GNU-stack,"",%progbits
